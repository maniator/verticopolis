//! The catalog table: one `fac!` row per facility, in `Kind` order.

use super::{Category, Facility, Kind};

macro_rules! fac {
    ($kind:ident, $key:literal, $cat:ident, $name:literal, $w:literal, $floors:expr, $cost:literal, $star:literal, $pop:literal, $att:expr, mo=$mo:literal, t=$t:literal, so=$so:literal, b=$b:literal) => {
        Facility {
            kind: Kind::$kind,
            key: $key,
            category: Category::$cat,
            name: $name,
            width: $w,
            floors: $floors,
            cost: $cost as f64,
            min_star: $star,
            population: $pop,
            attendance: $att,
            modern_only: $mo,
            transport: $t,
            staff_only: $so,
            basement: $b,
        }
    };
}

mod rest;

const fn join<const N: usize>(head: &[Facility], tail: &[Facility]) -> [Facility; N] {
    let mut out = [head[0]; N];
    let mut i = 0;
    while i < head.len() {
        out[i] = head[i];
        i += 1;
    }
    let mut j = 0;
    while j < tail.len() {
        out[head.len() + j] = tail[j];
        j += 1;
    }
    out
}

