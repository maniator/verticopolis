/**
 * Write `src/public/splash-skyline.svg`, the title screen's skyline as an
 * image for the docs site's landing page, from the shapes the game draws
 * inline (`src/ui/splashSkyline.ts`) and the two splash colors the game
 * paints them with (`--splash-building`, `--splash-ink` in the components'
 * `retro-tokens.css`).
 *
 *   node scripts/gen-splash-skyline.ts    regenerate the image
 *   npm run skyline:check                 regenerate, then fail on any difference
 *
 * Keep this file ERASABLE (see screenshot-env.ts) so `node` runs it directly.
 */
// It reads two of the project's own color tokens and copies no third-party
// package content.
// copies-package: none
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SKYLINE_BUILDINGS,
  SKYLINE_VIEWBOX,
  SKYLINE_WINDOWS,
  SKYLINE_WINDOW_COLOR,
  SKYLINE_WINDOW_SIZE,
} from "../src/ui/splashSkyline.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/public/splash-skyline.svg");

const components = dirname(createRequire(import.meta.url).resolve("@verticopolis/components/package.json"));
const tokens = readFileSync(resolve(components, "lib/styles/retro-tokens.css"), "utf8");

/** A `--splash-*` color as `retro-tokens.css` declares it. */
function color(name: string): string {
  const m = new RegExp(`--${name}:\\s*(#[0-9a-fA-F]{3,8})\\s*;`).exec(tokens);
  if (!m) throw new Error(`gen-splash-skyline: retro-tokens.css declares no --${name} color`);
  return m[1];
}

const { width, height } = SKYLINE_WINDOW_SIZE;
const rect = ([x, y]: readonly [number, number]) => `<rect x="${x}" y="${y}" width="${width}" height="${height}" />`;
const windowLines: string[] = [];
for (let i = 0; i < SKYLINE_WINDOWS.length; i += 2) {
  windowLines.push(`    ${SKYLINE_WINDOWS.slice(i, i + 2).map(rect).join("")}`);
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${SKYLINE_VIEWBOX}">
  <!-- AUTO-GENERATED by scripts/gen-splash-skyline.ts; do not edit. The title
       screen's skyline for pages that draw it as an image (the docs site's
       landing page). The game draws the same shapes inline
       (src/ui/splashSkyline.ts) and colors them from the splash tokens. -->
  <g fill="${color("splash-building")}" stroke="${color("splash-ink")}" stroke-width="1">
${SKYLINE_BUILDINGS.map((d) => `    <path d="${d}" />`).join("\n")}
  </g>
  <g fill="${SKYLINE_WINDOW_COLOR}">
${windowLines.join("\n")}
  </g>
</svg>
`;

writeFileSync(OUT, svg);
console.log(`gen-splash-skyline: wrote ${SKYLINE_BUILDINGS.length} buildings and ${SKYLINE_WINDOWS.length} windows to src/public/splash-skyline.svg`);
